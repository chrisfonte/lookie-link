'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const yaml = require('js-yaml');

const ROOT = path.resolve(__dirname, '..');
const SPEC_PATH = path.join(ROOT, 'docs', 'SKILL-SPEC.md');
const OUTPUT_ROOT = path.join(ROOT, 'generated', 'skill-packages');
const GENERATED_SECTIONS = [
  'Setup',
  'Authentication',
  'Quick reference',
  'When to use this skill',
  'When to use the API directly vs the CLI',
  'Decision matrix',
  'Concurrency and conflict handling',
  'Common workflows',
  'Error handling',
];

function extractSection(markdown, heading) {
  const escaped = heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const pattern = new RegExp(`^## ${escaped}\\r?\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, 'm');
  const match = markdown.match(pattern);
  if (!match || !match[1].trim()) throw new Error(`Missing required section: ${heading}`);
  return match[1].trim();
}

function extractFrontmatter(markdown) {
  const section = extractSection(markdown, 'Frontmatter');
  const match = section.match(/^```yaml\r?\n([\s\S]*?)\r?\n```$/);
  if (!match) throw new Error('Frontmatter must contain exactly one YAML code block.');
  const frontmatter = match[1].trim();
  const parsed = yaml.load(frontmatter);
  if (!parsed || typeof parsed.name !== 'string' || typeof parsed.description !== 'string') {
    throw new Error('Frontmatter requires string name and description fields.');
  }
  return frontmatter;
}

function sourceHash(spec) {
  return crypto.createHash('sha256').update(spec, 'utf8').digest('hex');
}

function generatedBody(spec, hash) {
  const sections = GENERATED_SECTIONS
    .map((heading) => `## ${heading}\n\n${extractSection(spec, heading)}`)
    .join('\n\n');
  return [
    '# Lookie-Link',
    '',
    'Generated from `docs/SKILL-SPEC.md`; do not edit this file directly.',
    '',
    `Source SHA-256: \`${hash}\``,
    '',
    sections,
    '',
  ].join('\n');
}

function buildSkill(spec, hash) {
  return `---\n${extractFrontmatter(spec)}\n---\n\n${generatedBody(spec, hash)}`;
}

function buildCursorRules(spec, hash) {
  return [
    '# Lookie-Link Cursor Rules',
    '',
    'Generated from `docs/SKILL-SPEC.md`; do not edit this file directly.',
    '',
    `Source SHA-256: \`${hash}\``,
    '',
    ...GENERATED_SECTIONS.map((heading) => `## ${heading}\n\n${extractSection(spec, heading)}\n`),
  ].join('\n');
}

function buildOutputs(spec) {
  const hash = sourceHash(spec);
  const outputNames = [
    'claude-code/lookie-link/SKILL.md',
    'codex/lookie-link/SKILL.md',
    'cursor/lookie-link/.cursorrules',
  ].sort();
  const outputs = new Map([
    [outputNames[0], outputNames[0].startsWith('cursor/') ? buildCursorRules(spec, hash) : buildSkill(spec, hash)],
    [outputNames[1], outputNames[1].startsWith('cursor/') ? buildCursorRules(spec, hash) : buildSkill(spec, hash)],
    [outputNames[2], outputNames[2].startsWith('cursor/') ? buildCursorRules(spec, hash) : buildSkill(spec, hash)],
  ]);
  outputs.set('manifest.json', `${JSON.stringify({
    schemaVersion: 1,
    source: 'docs/SKILL-SPEC.md',
    sourceHash: hash,
    generator: 'scripts/generate-skill-packages.js',
    outputs: outputNames,
  }, null, 2)}\n`);
  return outputs;
}

async function listFiles(directory, prefix = '') {
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error && error.code === 'ENOENT') return [];
    throw error;
  }
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await listFiles(path.join(directory, entry.name), relativePath));
    else if (entry.isFile()) files.push(relativePath);
    else files.push(relativePath);
  }
  return files;
}

async function inspectDrift(outputs) {
  const drift = [];
  for (const [relativePath, expected] of outputs) {
    try {
      const current = await fs.readFile(path.join(OUTPUT_ROOT, relativePath), 'utf8');
      if (current !== expected) drift.push({ relativePath, reason: 'changed' });
    } catch (error) {
      if (error && error.code === 'ENOENT') drift.push({ relativePath, reason: 'missing' });
      else throw error;
    }
  }
  for (const relativePath of await listFiles(OUTPUT_ROOT)) {
    if (!outputs.has(relativePath)) drift.push({ relativePath, reason: 'unexpected' });
  }
  return drift.sort((left, right) => left.relativePath.localeCompare(right.relativePath));
}

async function writeOutputs(outputs, drift) {
  for (const { relativePath, reason } of drift) {
    const targetPath = path.join(OUTPUT_ROOT, relativePath);
    if (reason === 'unexpected') {
      await fs.unlink(targetPath);
      continue;
    }
    await fs.mkdir(path.dirname(targetPath), { recursive: true });
    await fs.writeFile(targetPath, outputs.get(relativePath), 'utf8');
  }
}

async function main(argv = process.argv.slice(2)) {
  const unknown = argv.filter((arg) => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown option: ${unknown[0]}`);
  const checkOnly = argv.includes('--check');
  const spec = (await fs.readFile(SPEC_PATH, 'utf8')).replace(/\r\n/g, '\n');
  const outputs = buildOutputs(spec);
  const drift = await inspectDrift(outputs);
  if (!drift.length) return;
  if (checkOnly) {
    for (const item of drift) process.stderr.write(`${item.reason}: generated/skill-packages/${item.relativePath}\n`);
    process.stderr.write('Generated skill packages are stale. Run `npm run generate:skill-packages`.\n');
    process.exitCode = 1;
    return;
  }
  await writeOutputs(outputs, drift);
}

if (require.main === module) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}

module.exports = { buildOutputs, extractFrontmatter, extractSection, inspectDrift, main, sourceHash };
